-- INC_LOAD_FACT_SALES
CREATE OR REPLACE EDITIONABLE PROCEDURE "INC_LOAD_FACT_SALES" (
    LOAD_DATE IN DATE
) AS
BEGIN
    MERGE INTO FACT_SALES TGT
    USING (
        SELECT
            DATE_KEY,
            SITE_KEY,
            PRODUCT_KEY,
            SHIPTO_KEY,
            CARRIER_KEY,
            CUSTOMER_KEY,
            SUM(SHIPPED_CWT) AS SHIPPED_CWT,
            SUM(VOLUME) AS VOLUME,
            SUM(MILES) AS MILES,
            SUM(SITE_GOAL) AS SITE_GOAL,
            SUM(VAR_TO_GOAL) AS VAR_TO_GOAL
        FROM (
            SELECT
                D.DATE_KEY,
                DS.SITE_KEY,
                DP.PRODUCT_KEY,
                DST.SHIPTO_KEY,
                DCAR.CARRIER_KEY,
                DCUST.CUSTOMER_KEY,
                F.SHIPPED_CWT,
                F.VOLUME,
                F.MILES,
                F.SITE_GOAL,
                F.VAR_TO_GOAL
            FROM ARD_OPS_FILLORDER F
            LEFT JOIN ARD_OPS_SALESORDER SO
                ON SO.ORDER_NO = TO_CHAR(F.ORDER_NUMBER)
            LEFT JOIN DIM_CUSTOMER DCUST
                ON DCUST.CUSTOMER_ID = SO.CUSTOMER_ID
            JOIN DIM_DATE D
                ON D.FULL_DATE = TRUNC(F.SHIP_DATE)
            LEFT JOIN DIM_SITE DS
                ON DS.SITE_ID = F.SITE_ID
               AND DS.ACTIVE_FLAG = 'YES'
            LEFT JOIN DIM_PRODUCT DP
                ON DP.PRODUCT_ID = F.PRODUCT_ID
               AND DP.ACTIVE_FLAG = 'YES'
            LEFT JOIN DIM_SHIPTO DST
                ON DST.SHIP_TO_ID = F.SHIP_TO_ID
               AND DST.ACTIVE_FLAG = 'YES'
            LEFT JOIN DIM_CARRIER DCAR
                ON DCAR.CARRIER_ID = F.CARRIER_ID
            WHERE F.SHIP_DATE IS NOT NULL
              AND (F.CREATED_DATE > LOAD_DATE
                   OR NVL(F.UPDATED_DATE, F.CREATED_DATE) > LOAD_DATE)
        )
        GROUP BY
            DATE_KEY,
            SITE_KEY,
            PRODUCT_KEY,
            SHIPTO_KEY,
            CARRIER_KEY,
            CUSTOMER_KEY
    ) SRC
    ON (
        TGT.DATE_KEY = SRC.DATE_KEY
        AND NVL(TGT.SITE_KEY, -1) = NVL(SRC.SITE_KEY, -1)
        AND NVL(TGT.PRODUCT_KEY, -1) = NVL(SRC.PRODUCT_KEY, -1)
        AND NVL(TGT.SHIPTO_KEY, -1) = NVL(SRC.SHIPTO_KEY, -1)
        AND NVL(TGT.CARRIER_KEY, -1) = NVL(SRC.CARRIER_KEY, -1)
        AND NVL(TGT.CUSTOMER_KEY, -1) = NVL(SRC.CUSTOMER_KEY, -1)
    )
    WHEN MATCHED THEN
        UPDATE SET
            TGT.SHIPPED_CWT = SRC.SHIPPED_CWT,
            TGT.VOLUME = SRC.VOLUME,
            TGT.MILES = SRC.MILES,
            TGT.SITE_GOAL = SRC.SITE_GOAL,
            TGT.VAR_TO_GOAL = SRC.VAR_TO_GOAL
    WHEN NOT MATCHED THEN
        INSERT (
            DATE_KEY, SITE_KEY, PRODUCT_KEY, SHIPTO_KEY, CARRIER_KEY,
            CUSTOMER_KEY, SHIPPED_CWT, VOLUME, MILES, SITE_GOAL, VAR_TO_GOAL
        )
        VALUES (
            SRC.DATE_KEY, SRC.SITE_KEY, SRC.PRODUCT_KEY, SRC.SHIPTO_KEY,
            SRC.CARRIER_KEY, SRC.CUSTOMER_KEY, SRC.SHIPPED_CWT, SRC.VOLUME,
            SRC.MILES, SRC.SITE_GOAL, SRC.VAR_TO_GOAL
        );

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
