            D.DATE_KEY,
            DB.BIN_KEY,
            DCT.CLEANING_KEY,
            DS.SITE_KEY,
            MAX(BCL.DAYS_SINCE_LAST_CLEANING) AS DAYS_SINCE_LAST_CLEANING,
