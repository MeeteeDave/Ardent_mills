-- RUN_INCREMENTAL_OLAP_LOAD
CREATE OR REPLACE EDITIONABLE PROCEDURE "RUN_INCREMENTAL_OLAP_LOAD" (
    P_LOAD_DATE IN DATE DEFAULT NULL
) AS
    -- Orchestrates the full incremental OLAP refresh.
    --
    -- Every dimension loads before any fact: a fact row resolves its foreign
    -- keys by looking the business key up in the dimension, so a fact loaded
    -- against a stale dimension would miss the lookup and drop or misassign
    -- the row.
    --
    -- P_LOAD_DATE overrides the watermark; when NULL the last successful
    -- watermark is read from ETL_LOAD_CONTROL.
    --
    -- Note on atomicity: each INC_LOAD_* procedure commits its own work, so a
    -- mid-run failure leaves earlier steps committed. That is safe here because
    -- every step is a MERGE keyed on the business key, and the watermark is
    -- only advanced on full success -- so a re-run reprocesses the same window
    -- and converges. Do not advance LAST_LOAD_DATE in the exception handler.
    C_PROCESS         CONSTANT VARCHAR2(100) := 'OLAP_INCREMENTAL_LOAD';
    C_FIRST_LOAD      CONSTANT DATE          := DATE '1900-01-01';
    V_LAST_LOAD_DATE  DATE;
    V_LOAD_START_DATE DATE := SYSDATE;
BEGIN
    IF P_LOAD_DATE IS NOT NULL THEN
        V_LAST_LOAD_DATE := P_LOAD_DATE;
    ELSE
        BEGIN
            SELECT LAST_LOAD_DATE
              INTO V_LAST_LOAD_DATE
              FROM ETL_LOAD_CONTROL
             WHERE PROCESS_NAME = C_PROCESS;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                V_LAST_LOAD_DATE := NULL;   -- first ever run
        END;
    END IF;

    V_LAST_LOAD_DATE := NVL(V_LAST_LOAD_DATE, C_FIRST_LOAD);

    ---------------------------------------------------------------- dimensions
    INC_LOAD_DIM_DATE(V_LAST_LOAD_DATE);
    INC_LOAD_DIM_SITE(V_LAST_LOAD_DATE);
    INC_LOAD_DIM_PRODUCT(V_LAST_LOAD_DATE);
    INC_LOAD_DIM_CUSTOMER(V_LAST_LOAD_DATE);
    INC_LOAD_DIM_SHIPTO(V_LAST_LOAD_DATE);
    INC_LOAD_DIM_CARRIER(V_LAST_LOAD_DATE);
    INC_LOAD_DIM_PACKLINE(V_LAST_LOAD_DATE);
    INC_LOAD_DIM_MAINTENANCE_TYPE(V_LAST_LOAD_DATE);
    INC_LOAD_DIM_BIN(V_LAST_LOAD_DATE);
    INC_LOAD_DIM_CLEANING_TYPE(V_LAST_LOAD_DATE);
    INC_LOAD_DIM_PRODUCTION_MIX(V_LAST_LOAD_DATE);

    --------------------------------------------------------------------- facts
    INC_LOAD_FACT_SALES(V_LAST_LOAD_DATE);
    INC_LOAD_FACT_PACK_PRODUCTION(V_LAST_LOAD_DATE);
    INC_LOAD_FACT_MILL_PRODUCTION(V_LAST_LOAD_DATE);
    INC_LOAD_FACT_MAINTENANCE(V_LAST_LOAD_DATE);
    INC_LOAD_FACT_BIN_CLEANING(V_LAST_LOAD_DATE);

    -- MERGE, not UPDATE: a missing control row would otherwise silently update
    -- zero rows and leave the watermark unset, reprocessing everything forever.
    MERGE INTO ETL_LOAD_CONTROL tgt
    USING (SELECT C_PROCESS AS PROCESS_NAME FROM DUAL) src
       ON (tgt.PROCESS_NAME = src.PROCESS_NAME)
    WHEN MATCHED THEN
        UPDATE SET tgt.LAST_LOAD_DATE    = V_LOAD_START_DATE,
                   tgt.LAST_SUCCESS_DATE = SYSDATE,
                   tgt.STATUS            = 'SUCCESS'
    WHEN NOT MATCHED THEN
        INSERT (PROCESS_NAME, LAST_LOAD_DATE, LAST_SUCCESS_DATE, STATUS)
        VALUES (C_PROCESS, V_LOAD_START_DATE, SYSDATE, 'SUCCESS');

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;

        UPDATE ETL_LOAD_CONTROL
           SET STATUS = 'FAILED'
         WHERE PROCESS_NAME = C_PROCESS;

        COMMIT;
        RAISE;
END;
