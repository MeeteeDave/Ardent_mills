            ON DS.SITE_ID = DB.SITE_ID
           AND DS.ACTIVE_FLAG = 'YES'
        WHERE BCL.CLEANING_COMPLETED_ON IS NOT NULL
          AND (BCL.CREATED_DATE > LOAD_DATE
               OR NVL(BCL.UPDATED_DATE, BCL.CREATED_DATE) > LOAD_DATE)
        GROUP BY
            D.DATE_KEY,
            DB.BIN_KEY,
            DCT.CLEANING_KEY,
            DS.SITE_KEY
