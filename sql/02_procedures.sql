-- INC_LOAD_DIM_DATE
CREATE OR REPLACE EDITIONABLE PROCEDURE "INC_LOAD_DIM_DATE" (
    LOAD_DATE IN DATE
) AS
BEGIN
    INSERT INTO DIM_DATE (
        FULL_DATE,
        DAY,
        MONTH,
        MONTH_NAME,
        QUARTER,
        YEAR,
        WEEK,
        CREATED_DATE,
        CREATED_BY
    )
    SELECT
        DT.FULL_DATE,
        EXTRACT(DAY FROM DT.FULL_DATE),
        EXTRACT(MONTH FROM DT.FULL_DATE),
        TRIM(TO_CHAR(DT.FULL_DATE, 'MONTH')),
        TO_NUMBER(TO_CHAR(DT.FULL_DATE, 'Q')),
        EXTRACT(YEAR FROM DT.FULL_DATE),
        TO_NUMBER(TO_CHAR(DT.FULL_DATE, 'IW')),
        SYSDATE,
        USER
    FROM (
        SELECT TRUNC(PACK_DATE) AS FULL_DATE
        FROM ARD_OPS_PACKRUN
        WHERE PACK_DATE IS NOT NULL
        UNION
        SELECT TRUNC(MILL_DATE)
        FROM ARD_OPS_MILLRUN
        WHERE MILL_DATE IS NOT NULL
        UNION
        SELECT TRUNC(SHIP_DATE)
        FROM ARD_OPS_SALESORDER
        WHERE SHIP_DATE IS NOT NULL
        UNION
        SELECT TRUNC(REQUIRED_DATE)
        FROM ARD_OPS_WORKORDER
        WHERE REQUIRED_DATE IS NOT NULL
        UNION
        SELECT TRUNC(CLEANING_COMPLETED_ON)
        FROM ARD_OPS_BINCLEANINGLOG
        WHERE CLEANING_COMPLETED_ON IS NOT NULL
        UNION
        SELECT TRUNC(SHIP_DATE)
        FROM ARD_OPS_FILLORDER
        WHERE SHIP_DATE IS NOT NULL
    ) DT
    WHERE NOT EXISTS (
        SELECT 1
        FROM DIM_DATE D
        WHERE D.FULL_DATE = DT.FULL_DATE
    );

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
